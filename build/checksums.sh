# Writes DIR/checksums.txt (sha256sum format: "<hash>  <file>") for all
# regular files in DIR (default dist/), excluding signatures and the file itself.
# Verify with:  sha256sum -c checksums.txt   (or --ignore-missing for single files)
set -eu
# shellcheck source=lib.sh
. "$(dirname "$0")/lib.sh"

dir=${1:-$DIST}
cd "$dir"
files=$(find . -maxdepth 1 -type f ! -name checksums.txt ! -name 'checksums.txt.*' ! -name '*.asc' ! -name '*.sig' \
	-printf '%f\n' | LC_ALL=C sort)
[ -n "$files" ] || die "no files in $dir"
# shellcheck disable=SC2086 # file names are generated by our scripts and contain no spaces
sha256 $files > checksums.txt
log "wrote $dir/checksums.txt ($(wc -l < checksums.txt) files)"
cat checksums.txt
