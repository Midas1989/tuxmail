// Package push sends Web Push notifications (RFC 8030, message encryption
// RFC 8291, VAPID RFC 8292) to the installed PWA on Android, desktop browsers
// and iOS/iPadOS 16.4+ (where Web Push only works for PWAs added to the home
// screen). Encryption and VAPID signing are done by
// github.com/SherClockHolmes/webpush-go.
//
// Other components (mail sync, messenger bridges, calendar) call the Notifier
// interface; user preferences (enabled, quiet hours, per-account/channel
// toggles, privacy mode) are applied here.
package push

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"log/slog"
	"net/http"
	"os"
	"strings"
	"time"

	webpush "github.com/SherClockHolmes/webpush-go"
)

// Payload is the JSON document delivered to the service worker.
type Payload struct {
	Type           string `json:"type"` // mail | chat | calendar | system ...
	Title          string `json:"title"`
	Body           string `json:"body"`
	URL            string `json:"url,omitempty"`
	Tag            string `json:"tag,omitempty"`
	AccountID      string `json:"accountId,omitempty"`
	ConversationID string `json:"conversationId,omitempty"`
	// Optional fields for native notifications (mobile/SERVER_TODO.md 2).
	Sender string `json:"sender,omitempty"` // display name of the sender (MessagingStyle)
	ItemID string `json:"itemId,omitempty"` // item a quick reply answers
	// TeamID is set for conversations of a shared team mailbox: the
	// conversation id then refers to the team store (KONZEPT 8.14).
	TeamID string `json:"teamId,omitempty"`
	// Badge is the unread counter for the app icon (Badging API); 0 = unchanged.
	Badge int `json:"badge,omitempty"`
}

// Urgency values (RFC 8030 section 5.3).
const (
	UrgencyVeryLow = "very-low"
	UrgencyLow     = "low"
	UrgencyNormal  = "normal"
	UrgencyHigh    = "high"
)

// Notification is a payload plus delivery options.
type Notification struct {
	Payload
	TTL     time.Duration // how long the push service keeps it; default 24h
	Urgency string        // default normal
	Topic   string        // replaces an undelivered message with the same topic (max 32 base64url chars)
}

// Notifier is implemented by Sender; other packages depend only on this.
type Notifier interface {
	Notify(ctx context.Context, userID int64, n Notification) error
}

// PrivacyBody is shown instead of the content in privacy mode.
const (
	PrivacyTitle = "TuxMail"
	PrivacyBody  = "Neue Nachricht"
)

// Keys is a VAPID key pair (base64url, as generated by webpush-go).
type Keys struct {
	PublicKey  string `json:"publicKey"`
	PrivateKey string `json:"privateKey"`
}

// LoadOrCreateKeys reads the VAPID key pair at path or generates it on first
// start (file mode 0600). Changing the keys invalidates all subscriptions.
func LoadOrCreateKeys(path string) (Keys, error) {
	var k Keys
	data, err := os.ReadFile(path)
	if err == nil {
		if err := json.Unmarshal(data, &k); err != nil || k.PublicKey == "" || k.PrivateKey == "" {
			return Keys{}, fmt.Errorf("push: malformed VAPID key file %s", path)
		}
		return k, nil
	}
	if !errors.Is(err, fs.ErrNotExist) {
		return Keys{}, fmt.Errorf("push: %w", err)
	}
	k.PrivateKey, k.PublicKey, err = webpush.GenerateVAPIDKeys()
	if err != nil {
		return Keys{}, err
	}
	data, _ = json.MarshalIndent(k, "", "  ")
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		return Keys{}, fmt.Errorf("push: create VAPID keys: %w", err)
	}
	if _, err := f.Write(data); err != nil {
		f.Close()
		os.Remove(path)
		return Keys{}, err
	}
	return k, f.Close()
}

// Sender delivers notifications to all subscriptions of a user.
type Sender struct {
	Store      *Store
	Keys       Keys
	Subscriber string // "https://..." or an email address (VAPID "sub" claim)
	HTTPClient *http.Client
	Log        *slog.Logger
	Now        func() time.Time
	// FCM delivers to Firebase Cloud Messaging registrations (sender_fcm.go);
	// nil when push.fcm is not configured.
	FCM FCMClient
	// dedupe suppresses the same notification (user + tag) within a short
	// window, e.g. when two producers report the same mail (dedupe.go).
	dedupe deduper
}

var _ Notifier = (*Sender)(nil)

// ErrSuppressed is returned when preferences prevent delivery.
var ErrSuppressed = errors.New("push: suppressed by user preferences")

// Notify applies the user's preferences and sends n to every subscription.
// Subscriptions answered with 404/410 are removed. It returns ErrSuppressed
// if preferences block the notification and a joined error of failed
// deliveries otherwise.
func (s *Sender) Notify(ctx context.Context, userID int64, n Notification) error {
	prefs, err := s.Store.Prefs(ctx, userID)
	if err != nil {
		return err
	}
	now := time.Now()
	if s.Now != nil {
		now = s.Now()
	}
	p, ok := prefs.Apply(n.Payload, now)
	if !ok {
		return ErrSuppressed
	}
	n.Payload = p
	if !s.dedupe.first(userID, n.Tag, now) {
		return ErrDuplicate
	}
	subs, err := s.Store.List(ctx, userID)
	if err != nil {
		return err
	}
	subs = OnePerSession(subs)
	var errs []error
	for _, sub := range subs {
		if err := s.send(ctx, sub, n); err != nil {
			errs = append(errs, err)
		}
	}
	return errors.Join(errs...)
}

// SendTo delivers n to one subscription without applying preferences.
func (s *Sender) SendTo(ctx context.Context, sub Subscription, n Notification) error {
	return s.send(ctx, sub, n)
}

func (s *Sender) send(ctx context.Context, sub Subscription, n Notification) error {
	if sub.Kind == KindFCM {
		return s.sendFCM(ctx, sub, n)
	}
	body, err := json.Marshal(n.Payload)
	if err != nil {
		return err
	}
	ttl := n.TTL
	if ttl <= 0 {
		ttl = 24 * time.Hour
	}
	urg := n.Urgency
	if urg == "" {
		urg = UrgencyNormal
	}
	client := s.HTTPClient
	if client == nil {
		client = &http.Client{Timeout: 30 * time.Second}
	}
	resp, err := webpush.SendNotificationWithContext(ctx, body, &webpush.Subscription{
		Endpoint: sub.Endpoint,
		Keys:     webpush.Keys{Auth: sub.Auth, P256dh: sub.P256dh},
	}, &webpush.Options{
		HTTPClient:      client,
		Subscriber:      s.Subscriber,
		Topic:           n.Topic,
		TTL:             int(ttl / time.Second),
		Urgency:         webpush.Urgency(urg),
		VAPIDPublicKey:  s.Keys.PublicKey,
		VAPIDPrivateKey: s.Keys.PrivateKey,
	})
	if err != nil {
		return fmt.Errorf("push: send to %s: %w", endpointHost(sub.Endpoint), err)
	}
	defer resp.Body.Close()
	io.Copy(io.Discard, io.LimitReader(resp.Body, 64<<10))
	switch {
	case resp.StatusCode == http.StatusNotFound || resp.StatusCode == http.StatusGone:
		if s.Log != nil {
			s.Log.Info("push subscription expired, removing", "user", sub.UserID, "endpoint_host", endpointHost(sub.Endpoint))
		}
		return s.Store.DeleteEndpoint(context.WithoutCancel(ctx), sub.Endpoint)
	case resp.StatusCode >= 200 && resp.StatusCode < 300:
		return s.Store.MarkSuccess(ctx, sub.ID)
	default:
		return fmt.Errorf("push: %s answered %s", endpointHost(sub.Endpoint), resp.Status)
	}
}

func endpointHost(endpoint string) string {
	rest, _ := strings.CutPrefix(endpoint, "https://")
	host, _, _ := strings.Cut(rest, "/")
	return host
}
